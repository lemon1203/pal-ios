def utf8(text):
    return ''.join('\\x%02x' % b for b in text.encode('utf-8'))


def build_label_block():
    lines = ['// UTF-8 label bytes, generated by apply_cheats.py']
    for key, text in LABELS:
        lines.append('static const unsigned char lb_%s[] = "%s";' % (key, utf8(text)))
    return '\n'.join(lines)


